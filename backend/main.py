@app.get("/")
def index():
    """The whole frontend, served with revalidation forced on every load.

    Without Cache-Control a browser applies *heuristic* freshness to a response
    that only carries Last-Modified/ETag, and happily reuses it without asking
    us — roughly 10% of the document's age, so a page that had been up for two
    days stayed cached for hours. That is not a cosmetic problem here: the app
    is one HTML file talking to an API it has to agree with, and after a deploy
    a stale page fails in confusing ways (clarifying questions became objects
    server-side and the old page rendered them as "[object Object]").

    'no-cache' does not mean "do not store" — the browser keeps the file and
    revalidates, so an unchanged page still costs one 304 and no download.
    """
    return FileResponse(FRONTEND, headers={"Cache-Control": "no-cache"})

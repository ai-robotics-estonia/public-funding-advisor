@app.post("/login")
def login(req: LoginRequest, request: Request, response: Response):
    rate_limit.check_rate_limit(request)
    if not auth.enabled():
        return {"ok": True, "auth": "disabled"}
    tester = auth.login(req.code)
    if tester is None:
        _mark(request, action="login_failed")
        raise HTTPException(status_code=401, detail="tundmatu kood")
    auth.set_session_cookie(response, tester["tester_id"])
    _mark(request, action="login", detail={"tester": tester["name"]})
    return {"ok": True, "name": tester["name"]}


@app.post("/logout")
def logout(request: Request, response: Response):
    _mark(request, action="logout")
    auth.clear_session_cookie(response)
    return {"ok": True}


@app.get("/me")
def me(request: Request):
    """Who am I — lets the frontend decide whether to show the login overlay."""
    if not auth.enabled():
        return {"authenticated": True, "auth": "disabled"}
    tester_id = getattr(request.state, "tester_id", None)
    tester = db.get_tester(tester_id) if tester_id else None
    if tester is None or not tester["active"]:
        return {"authenticated": False}
    return {"authenticated": True, "name": tester["name"]}



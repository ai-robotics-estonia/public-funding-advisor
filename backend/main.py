@asynccontextmanager
async def lifespan(app: FastAPI):
    """Everything that touches the database or the network, run once on startup.

    Deliberately NOT at module scope. Importing this module has to stay a pure
    import: the test suite does `from backend.main import app` before its
    fixtures redirect db.DATA_DIR at a tmp_path, so anything writing at import
    time writes the real data/app.db instead. Under uvicorn the lifespan runs
    before the first request is served, so production is unchanged.
    """
    db.init_db()
    log.info("db ready at %s", db.DB_PATH)

    # Retrieval index over the measure catalogue. Derived from the CSVs, so a
    # rebuild costs nothing but startup time — and a failure here must not stop
    # the API: search.select_candidates() falls back to keeping every candidate.
    try:
        search.reindex_if_stale(MEASURES)
    except Exception as exc:  # pragma: no cover - startup resilience
        log.warning("chunk index unavailable, retrieval will keep all candidates: %s", exc)

    if not auth.enabled():
        log.warning("AUTH_ENABLED is not set — every endpoint is open to anyone who can reach it")

    # Optional source-scraping background job. Import is guarded so a missing or
    # broken scraper package can never stop the API from starting.
    try:
        from scraper.scheduler import start_background_scheduler

        start_background_scheduler()
    except Exception as exc:  # pragma: no cover - startup resilience
        log.warning("scraper scheduler unavailable: %s", exc)

    yield



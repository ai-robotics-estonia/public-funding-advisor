@app.post("/threads/{thread_id}/messages")
def post_message(thread_id: str, req: MessageCreateRequest, request: Request,
                 tester=Depends(auth.require_tester)):
    rate_limit.check_rate_limit(request)
    thread = _owned_thread(request, thread_id)
    _mark(request, action="message_send", vestluse_id=thread["vestluse_id"], thread_id=thread_id)
    if not req.content.strip():
        raise HTTPException(status_code=400, detail="sõnum on tühi")

    recommendation = _recommendation(thread["vestluse_id"])
    if recommendation is None:
        raise HTTPException(status_code=409, detail="soovitust pole veel tehtud")
    measure = measures.get_measure_by_id(MEASURES, thread["measure_id"])
    if measure is None:
        raise HTTPException(status_code=404, detail="meedet ei leitud")

    refine_card = chat.find_refine_card(
        _refinement(thread["vestluse_id"]), thread["measure_id"]
    )
    history = db.list_messages(thread_id, limit=chat.MAX_HISTORY_MESSAGES)
    # After "clear history" the thread is empty — re-seed the focus card's own
    # pitch before the new user message so the thread doesn't open blank.
    if not history:
        seed = chat.seed_text(
            chat.find_focus_card(recommendation, thread["measure_id"]), refine_card
        )
        if seed:
            db.add_message(thread_id, "assistant", seed)
            history = db.list_messages(thread_id, limit=chat.MAX_HISTORY_MESSAGES)

    # Before storing the user's turn: a 429 here must not leave a message in the
    # thread that never got a reply.
    rate_limit.check_llm_rate_limit(request)
    db.add_message(thread_id, "user", req.content)

    try:
        reply_text = chat.send_message(
            thread["vestluse_id"], measure, recommendation, history, req.content, refine_card
        )
    except Exception as e:
        log.error("Claude call failed for thread %s: %s", thread_id, e)
        raise HTTPException(status_code=502, detail="vastust ei saadud")

    db.add_message(thread_id, "assistant", reply_text)
    return {"thread_id": thread_id, "messages": db.list_messages(thread_id)}



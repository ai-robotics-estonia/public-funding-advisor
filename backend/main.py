"""FastAPI app: vestlus (project) CRUD, file upload, and POST /recommend.

/recommend flow: the frontend sends the full intake form every time, scoped to
a vestluse_id.
- First call has empty 'clarifications' -> we run the hard-filter and return the
  surviving candidates plus deterministic clarifying questions. No Claude call,
  nothing persisted beyond the intake itself.
- Second call has 'clarifications' present (answers, or {} if the user skipped)
  -> we run the single Claude ranking call, using the vestlus's uploaded files as
  extra context, and save the result as that vestlus's one immutable
  recommendation snapshot. Any /recommend call once a snapshot exists is
  rejected (409) — a new vestluse_id is required for a new recommendation.

Every request passes through AuditMiddleware, which stamps a request_id, resolves
the caller's session, and writes one events row. Access control (backend/auth.py)
is off unless AUTH_ENABLED is set, so local development is unchanged.
"""


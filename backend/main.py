class AuditMiddleware:
    """Stamp every request with an id and identity, then record it in the audit trail.

    Written as raw ASGI rather than BaseHTTPMiddleware on purpose: Starlette runs
    BaseHTTPMiddleware's downstream app in a separate task, and context variables
    set before call_next do not reliably reach the route handler. Here everything
    happens in one task, so the request_id set below is the one llm.py sees when
    it writes an llm_calls row several frames deeper.
    """

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)

        request = Request(scope, receive=receive)
        rid = uuid.uuid4().hex[:16]
        audit.request_id.set(rid)
        audit.vestluse_id.set(None)

        tester_id = auth.cookie_tester(request)
        audit.tester_id.set(tester_id)
        # rate_limit and the route dependencies read identity from here.
        scope.setdefault("state", {})["tester_id"] = tester_id

        started = time.monotonic()
        status_holder = {"code": 500}

        async def send_wrapper(message):
            if message["type"] == "http.response.start":
                status_holder["code"] = message["status"]
            await send(message)

        try:
            await self.app(scope, receive, send_wrapper)
        finally:
            state = scope.get("state") or {}
            # Off the event loop: log_event writes to SQLite, and doing that
            # inline would serialise every request behind a disk write.
            await run_in_threadpool(
                audit.log_event,
                ip=request.client.host if request.client else None,
                method=scope.get("method"),
                path=scope.get("path"),
                action=state.get("action"),
                vestlus=state.get("vestluse_id"),
                thread_id=state.get("thread_id"),
                status_code=status_holder["code"],
                duration_ms=int((time.monotonic() - started) * 1000),
                detail=state.get("detail"),
            )


app.add_middleware(AuditMiddleware)


def _mark(request: Request, *, action: str | None = None, vestluse_id: str | None = None,
          thread_id: str | None = None, detail: dict | None = None) -> None:
    """Attach context to this request's audit row.

    vestluse_id is written twice on purpose: to request.state for the middleware
    (which runs back on the event loop and cannot see this thread's context) and
    to the context variable for llm.py (which runs deeper in this same thread).
    """
    if action:
        request.state.action = action
    if vestluse_id:
        request.state.vestluse_id = vestluse_id
        audit.vestluse_id.set(vestluse_id)
    if thread_id:
        request.state.thread_id = thread_id
    if detail:
        request.state.detail = detail


def _owned_vestlus(request: Request, vestluse_id: str) -> dict:
    """Fetch a vestlus, 404 if missing and 403 if it belongs to another tester."""
    vestlus = db.get_vestlus(vestluse_id)
    if vestlus is None:
        raise HTTPException(status_code=404, detail="vestlust ei leitud")
    auth.require_owner(request, vestlus["tester_id"])
    return vestlus


def _readable_vestlus(request: Request, vestluse_id: str) -> dict:
    """Fetch a vestlus the caller is allowed to READ.

    The owner always may. Anyone else may only if the owner explicitly saved it:
    saving is what turns the code into something meant to be handed to a
    colleague. Unsaved work stays private, and every other verb — upload,
    recommend, delete, chat — still goes through _owned_vestlus, so a shared
    code grants reading and nothing more.
    """
    vestlus = db.get_vestlus(vestluse_id)
    if vestlus is None:
        raise HTTPException(status_code=404, detail="vestlust ei leitud")

    owner = vestlus["tester_id"]
    caller = getattr(request.state, "tester_id", None)
    if not auth.enabled() or owner is None or caller == owner:
        return vestlus
    if not vestlus["saved"]:
        raise HTTPException(status_code=403, detail="see vestlus ei kuulu sulle")

    _mark(request, detail={"shared_read": True, "owner": owner})
    return vestlus


def _owned_thread(request: Request, thread_id: str) -> dict:
    """Fetch a thread and verify the caller owns the vestlus it belongs to.

    Without this a known thread_id was enough to read or extend anyone's chat —
    the handlers used to look the thread up and never ask whose it was.
    """
    thread = db.get_thread(thread_id)
    if thread is None:
        raise HTTPException(status_code=404, detail="threadi ei leitud")
    _owned_vestlus(request, thread["vestluse_id"])
    return thread


class RecommendRequest(BaseModel):
    vestluse_id: str
    intake: dict
    # None = first call (return questions). A dict (even empty, if the user
    # skipped) = second call (run ranking). This is why we key off None, not
    # emptiness — an empty dict still means "the user is done answering".
    clarifications: dict | None = None


class SaveRequest(BaseModel):
    title: str


class RefineRequest(BaseModel):
    measure_names: list[str]
    willing_to_change: str = ""


class ThreadCreateRequest(BaseModel):
    measure_id: str


class MessageCreateRequest(BaseModel):
    content: str


class LoginRequest(BaseModel):
    code: str


def _recommendation(vestluse_id: str) -> dict | None:
    """Salvestatud soovitus, mille allikaseis on värskeim, mis meil on.

    Soovitus ise on lukustatud hetktõmmis, aga `source_status` mitte — vt
    sources.refresh_cards(). Kõik lugejad käivad siit läbi, et vestlusesse
    minev fookuskaart ja UI näitaksid sama seisu.
    """
    return sources.refresh_cards(db.get_recommendation(vestluse_id), MEASURES)


def _refinement(vestluse_id: str) -> dict | None:
    """Viimane täiendava analüüsi käik, sama värske allikaseisuga kui soovitus.

    refresh_cards() ootab võtit "ranked_cards"; täiendava analüüsi kaartidel on
    sama kuju, nii et anname talle lihtsalt selle nime all sama listi.
    """
    refinement = db.get_latest_refinement(vestluse_id)
    if refinement:
        sources.refresh_cards({"ranked_cards": refinement["cards"]}, MEASURES)
    return refinement



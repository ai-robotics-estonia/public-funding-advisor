# Deliberately sync `def`: save_upload() writes up to 10 MB and then parses
# PDF/DOCX/XLSX, all blocking. As `async def` that ran on the event loop and
# stalled every other user's request for the duration of one big upload.
@app.post("/vestlused/{vestluse_id}/files")
def upload_file(vestluse_id: str, request: Request, file: UploadFile,
                tester=Depends(auth.require_tester)):
    rate_limit.check_rate_limit(request)
    _owned_vestlus(request, vestluse_id)
    # Files are locked to the pre-recommendation context; no uploads after ranking.
    if db.has_recommendation(vestluse_id):
        raise HTTPException(status_code=409, detail="soovitus on lukustatud, loo uus vestlus")
    try:
        filename = files.safe_filename(file.filename or "")
    except ValueError:
        raise HTTPException(status_code=400, detail="lubamatu failinimi")
    if not files.is_allowed(filename):
        raise HTTPException(status_code=400, detail="lubamatu failitüüp")

    data = file.file.read()
    if len(data) > files.MAX_FILE_BYTES:
        raise HTTPException(status_code=413, detail="fail on liiga suur (max 10 MB)")

    _mark(request, action="file_upload", vestluse_id=vestluse_id,
          detail={"name": filename, "bytes": len(data)})
    return files.save_upload(vestluse_id, filename, data)


@app.delete("/vestlused/{vestluse_id}/files/{file_id}")
def delete_file(vestluse_id: str, file_id: int, request: Request,
                tester=Depends(auth.require_tester)):
    rate_limit.check_rate_limit(request)
    _owned_vestlus(request, vestluse_id)
    # Single-file deletion is only allowed before the recommendation is locked.
    if db.has_recommendation(vestluse_id):
        raise HTTPException(status_code=409, detail="soovitus on lukustatud")
    path = db.delete_file(vestluse_id, file_id)
    if path is None:
        raise HTTPException(status_code=404, detail="faili ei leitud")
    if os.path.exists(path):
        os.remove(path)
    _mark(request, action="file_delete", vestluse_id=vestluse_id, detail={"file_id": file_id})
    return {"ok": True}


@app.post("/recommend")
def recommend(req: RecommendRequest, request: Request, tester=Depends(auth.require_tester)):
    rate_limit.check_rate_limit(request)
    _owned_vestlus(request, req.vestluse_id)
    _mark(request, action="recommend", vestluse_id=req.vestluse_id)
    if db.has_recommendation(req.vestluse_id):
        raise HTTPException(status_code=409, detail="soovitus on juba olemas, loo uus vestlus")

    db.update_vestlus_intake(req.vestluse_id, intake=req.intake, clarifications=req.clarifications)

    candidates, dropped = measures.filter_candidates(MEASURES, req.intake)
    names = [c["name"] for c in candidates]

    # First call: no clarifications yet -> return questions, skip the LLM.
    if req.clarifications is None:
        questions = measures.get_clarifying_questions(candidates)
        _mark(request, action="recommend_questions",
              detail={"candidates": len(names), "dropped": len(dropped)})
        return {"candidates": names, "questions": questions, "dropped": dropped, "ranked_cards": []}

    # Second call: user answered or skipped. The hard filter kept everyone this
    # applicant is eligible for; retrieval now narrows that to what the project
    # is actually about, so the ranking call sees the relevant measures rather
    # than the whole catalogue. Measures cut here stay visible in 'dropped'.
    query = search.build_query(req.intake, req.clarifications)
    candidates, cut = search.select_candidates(candidates, query)
    dropped = dropped + cut
    names = [c["name"] for c in candidates]

    # ...then the single Claude ranking call, using this vestlus's uploaded files
    # as extra context, and lock the snapshot.
    rate_limit.check_llm_rate_limit(request)
    files_context = files.build_context_text(req.vestluse_id)
    try:
        cards = rank(candidates, req.intake, req.clarifications, files_context)
    except Exception as e:
        log.error("Claude ranking call failed for %s: %s", req.vestluse_id, e)
        raise HTTPException(status_code=502, detail="soovitust ei õnnestunud koostada, proovi uuesti")
    try:
        db.save_recommendation(req.vestluse_id, names, dropped, cards)
    except ValueError:  # lost a race with a concurrent /recommend call
        raise HTTPException(status_code=409, detail="soovitus on juba olemas, loo uus vestlus")
    _mark(request, action="recommend_ranked",
          detail={"cards": len(cards), "rag_kept": len(names), "rag_cut": len(cut)})
    return {"candidates": names, "questions": [], "dropped": dropped, "ranked_cards": cards}


@app.post("/vestlused/{vestluse_id}/refine")
def refine_measures(vestluse_id: str, req: RefineRequest, request: Request,
                    tester=Depends(auth.require_tester)):
    """Second pass: what would have to change for the user's picked measures to fit.

    Only measures that survived the hard filter are eligible. A measure that was
    dropped was dropped on a company fact the applicant cannot edit, so no amount
    of rewriting the application would bring it back — accepting one here would
    promise something we cannot deliver.

    Owner-only, like every other write. Reading a shared vestlus does not entitle
    you to spend its owner's LLM budget on it.
    """
    rate_limit.check_rate_limit(request)
    vestlus = _owned_vestlus(request, vestluse_id)
    _mark(request, action="refine", vestluse_id=vestluse_id)

    recommendation = _recommendation(vestluse_id)
    if recommendation is None:
        raise HTTPException(status_code=409, detail="soovitust pole veel tehtud")

    eligible = set(recommendation["candidates"])
    requested = list(dict.fromkeys(req.measure_names))  # de-dupe, keep order
    if not requested:
        raise HTTPException(status_code=400, detail="vali vähemalt üks meede")
    unknown = [n for n in requested if n not in eligible]
    if unknown:
        raise HTTPException(
            status_code=400,
            detail=f"need meetmed ei ole valitavad: {', '.join(unknown)}",
        )

    by_name = {m["name"]: m for m in MEASURES}
    selected = [by_name[n] for n in requested if n in by_name]
    if not selected:
        raise HTTPException(status_code=400, detail="valitud meetmeid ei leitud")

    batches = math.ceil(len(selected) / refine.BATCH_SIZE)
    rate_limit.check_llm_rate_limit(request, cost=batches)

    prior_cards = {c["name"]: c for c in recommendation["ranked_cards"]}
    files_context = files.build_context_text(vestluse_id)
    cards, failed = refine.refine(
        selected,
        vestlus["intake"],
        vestlus["clarifications"] or {},
        files_context,
        prior_cards,
        req.willing_to_change.strip(),
    )
    if not cards:
        raise HTTPException(
            status_code=502, detail="analüüsi ei õnnestunud koostada, proovi uuesti"
        )

    db.save_refinement(vestluse_id, requested, req.willing_to_change.strip(), cards, failed)
    _mark(request, action="refine_done",
          detail={"cards": len(cards), "failed": len(failed), "batches": batches})
    return {"cards": cards, "failed": failed}


@app.post("/vestlused/{vestluse_id}/threads")
def create_thread(vestluse_id: str, req: ThreadCreateRequest, request: Request,
                  tester=Depends(auth.require_tester)):
    rate_limit.check_rate_limit(request)
    _owned_vestlus(request, vestluse_id)

    recommendation = _recommendation(vestluse_id)
    if recommendation is None:
        raise HTTPException(status_code=409, detail="soovitust pole veel tehtud")
    focus_card = chat.find_focus_card(recommendation, req.measure_id)
    # A measure can reach the chat through the second pass without ever having
    # been a ranked card, so either source makes it a legitimate focus.
    refine_card = chat.find_refine_card(_refinement(vestluse_id), req.measure_id)
    if focus_card is None and refine_card is None:
        raise HTTPException(status_code=404, detail="meedet ei leitud soovituse seast")

    thread_id, created = db.get_or_create_thread(vestluse_id, req.measure_id)
    _mark(request, action="thread_create", vestluse_id=vestluse_id, thread_id=thread_id,
          detail={"measure_id": req.measure_id, "created": created})
    if created:
        seed = chat.seed_text(focus_card, refine_card)
        if seed:
            db.add_message(thread_id, "assistant", seed)
    return {"thread_id": thread_id, "measure_id": req.measure_id, "created": created}



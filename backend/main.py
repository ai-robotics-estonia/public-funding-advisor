@app.post("/vestlused/{vestluse_id}/save")
def save_vestlus(vestluse_id: str, req: SaveRequest, request: Request,
                 tester=Depends(auth.require_tester)):
    """Keep this vestlus: name it, list it, and make its code shareable."""
    rate_limit.check_rate_limit(request)
    _owned_vestlus(request, vestluse_id)
    title = req.title.strip()
    if not title:
        raise HTTPException(status_code=400, detail="anna vestlusele nimi")
    if len(title) > 120:
        title = title[:120]
    _mark(request, action="vestlus_save", vestluse_id=vestluse_id)
    if not db.save_vestlus(vestluse_id, title):
        raise HTTPException(status_code=404, detail="vestlust ei leitud")
    return {"vestluse_id": vestluse_id, "title": title, "saved": True}


